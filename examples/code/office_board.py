"""Office building (3 floors): main switchboard and one distribution board per floor, generated in a loop.

uniwire "schematics as code" example. Run ``python office_board.py`` from any folder: it writes
``office_board.uniwire.json`` and ``office_board.pdf`` (one sheet per floor board) in the current folder.
"""

from itertools import cycle

from uniwire.build import *

# Reusable keyword sets
LIGHT = Template(curve="B", in_A=10, poles="1P+N", icn_kA=6,
                 product={"manufacturer": "Siemens", "range": "5SY6 MCB", "description": "MCB 1P+N B10 6 kA"})
SOCK = Template(curve="C", in_A=16, idn_mA=30, rcd_type="A", poles="1P+N", icn_kA=6,
                product={"manufacturer": "Siemens", "range": "5SV1 RCBO", "description": "RCBO 1P+N C16 30 mA type A"})
FEEDER = Template(in_A=63, curve="C", poles="4P", icn_kA=25)

FLOORS = [  # (level, label, lighting zones, socket zones, extra)
    (0, "Ground floor", ["Reception", "Open space", "Meeting rooms"], ["Reception desks", "Open space N", "Open space S"], "Café kitchenette"),
    (1, "First floor", ["Open space", "Offices", "Corridors"], ["Open space N", "Open space S", "Offices"], "Print room"),
    (2, "Second floor", ["Open space", "Offices", "Corridors"], ["Open space N", "Open space S", "Offices"], "Server room"),
]

with Installation("Office building (3 floors): main switchboard and floor distribution boards", earthing="TN-S",
                  system="3P+N", un="400 V", profiles=["iec60364"], lang="en", project="EX-C2",
                  author="uniwire examples", uln_V=230, ik3_kA=22, standard="IEC 60364",
                  notes=["Demonstrates the Python API: Template, floor boards generated by a for-loop, phase rotation, "
                         "own_sheet boards, off-page references to the lift (EX-46) and plant room (EX-48) drawings",
                         "Floor feeders 5G16 Cu XLPE on cable tray in the riser (method E), Iz checked by the iec60364 profile"]) as inst:
    with Grid("Utility LV supply", supply="400 V, 200 kVA"), \
            Meter("-P0", label="Utility meter", kind="CT 300/5 A"), \
            Board("MSB", label="Main switchboard", kind="main", in_A=250, ik_kA=22), \
            Breaker("-Q0", "250 A", ir_A=250, poles="4P", icu_kA=36, label="Incomer"):

        Breaker("-F0", "C32", poles="4P", icn_kA=25, label="SPD") >> SPD("-F01", type="1+2", imax_kA=50, up_kV=1.5)

        for level, name, lights, sockets, extra in FLOORS:
            riser = 6 + 4 * level  # m
            with Breaker(f"-Q{level + 1}", label=name, **FEEDER,
                         cable={"designation": "XLPE", "cores": "5G", "section_mm2": 16, "material": "Cu",
                                "insulation": "XLPE", "install": "E", "length_m": riser + 25}), \
                    Board(f"DB-{level}", label=f"{name} distribution board", kind="distribution", in_A=63, own_sheet=True), \
                    SwitchDisconnector("-Q0", "63 A", poles="4P", label="Main switch"):
                phases = cycle(["L1", "L2", "L3"])
                for i, zone in enumerate(lights, start=1):
                    Breaker(f"-F{i}", phase=next(phases), cable="3G1,5 30 m", **LIGHT) >> Lighting(f"{zone} lighting", points=12)
                for i, zone in enumerate(sockets, start=11):
                    RCBO(f"-F{i}", phase=next(phases), cable="3G2,5 35 m", **SOCK) >> Socket(f"{zone} sockets", points=10)
                if extra == "Server room":
                    with Breaker("-F21", "C32", poles="4P", icn_kA=10, cable="5G6 10 m", label="Server room"):
                        UPS("-U21", sn="10 kVA", autonomy_min=15, bypass=True) >> Load("IT racks", symbol_text="IT", p="8 kW")
                else:
                    RCBO("-F21", phase=next(phases), cable="3G2,5 15 m", label=extra, **{**SOCK, "in_A": 20}) >> \
                        Socket(f"{extra} sockets", points=6)
                Breaker("-F31", "C20", poles="4P", icn_kA=10, cable="5G4 20 m", label="Fan coils") >> \
                    Ventilation(f"{name} fan coil units", p="4.5 kW")
                Spare("-F40", in_A=16, poles="1P+N")

        Breaker("-Q7", "C40", poles="4P", icn_kA=25, label="Lift",
                cable={"cores": "5G", "section_mm2": 10, "material": "Cu", "insulation": "XLPE", "install": "E",
                       "length_m": 55}) >> OffPage("Lift machine room board", target="EX-46")
        Breaker("-Q12", "100 A", ir_A=80, poles="4P", icu_kA=36, label="Plant room",
                cable={"cores": "5G", "section_mm2": 25, "material": "Cu", "insulation": "XLPE", "install": "E",
                       "length_m": 45}) >> OffPage("TD-CVC plant room", target="EX-48")

    inst.view(id="sld", paper="A3", cartouche=["label", "ref", "protection", "idn_mA", "cable", "length_m", "phase", "p_kW"])

if __name__ == "__main__":
    for f in inst.check():
        print(f)
    inst.save("office_board.uniwire.json")
    print(inst.render("office_board.pdf"))
