@pytest.mark.parametrize("path", EXAMPLES, ids=lambda p: p.name[:2])
def test_describe_examples(path):
    doc = uniwire.load(path)
    text = describe(doc)
    assert text == describe(path)  # deterministic, same from a path or a Document
